"""Phase 3 Batch 02 (proposal): generate the Batch 02 override file from Phase 1 read-only evidence.
Usage: python -X utf8 p3b2_values.py <phase1_evidence_dir> <out_tex> <out_json>
Sources: R28/r28_20k_active.json (frozen R28 method, active graph 7aa6db46) and R09_R10/r10_recompute_out.json (Clopper-Pearson).
"""
import json, os, sys

P1, OUT_TEX, OUT_JSON = sys.argv[1:4]
r28 = json.load(open(os.path.join(P1, 'R28', 'r28_20k_active.json'), encoding='utf-8'))
assert r28['sha256'].startswith('7aa6db46'), 'R28 result must be for the active graph'
m = r28['M1_M2_undirected_largest_wcc']
assert m['largest_wcc_size'] == 18558
r10 = json.load(open(os.path.join(P1, 'R09_R10', 'r10_recompute_out.json'), encoding='utf-8'))
lo, hi = r10['clopper_pearson']['1/5']
vals = dict(diameter=m['diameter'], aspl=m['aspl'], wcc=m['largest_wcc_size'], ci_1_of_5=[lo, hi])
lines = ['% ==========================================================================',
         '% PHASE 3 BATCH 02 CORRECTION OVERRIDES (generated by p3b2_values.py; do not hand-edit)',
         '% R28: Table III diameter / ASPL were hard-coded 10k-graph values (15 / 4.713). Values below are the frozen',
         '%      R28 method (undirected graph, largest weakly connected component, exact BFS) on the ACTIVE 20k graph',
         f"%      sha256 {r28['sha256'][:16]}... (largest WCC {m['largest_wcc_size']} nodes).",
         '% R10-1: the 5-node Clopper-Pearson CI [47.8, 100.0] is the interval for 5/5 (legacy run); canonical v2 is 1/5.',
         '% ==========================================================================',
         f"\\renewcommand{{\\CorpusGraphDiameter}}{{{m['diameter']}}} % R28",
         f"\\renewcommand{{\\CorpusAvgShortestPath}}{{{m['aspl']:.3f}}} % R28 (exact {m['aspl']:.5f})",
         f"\\renewcommand{{\\CatBFiveNodeClopperPearsonCI}}{{[{lo:.1f}\\%, {hi:.1f}\\%]}} % R10-1: exact Clopper-Pearson 95% CI for 1/5"]
open(OUT_TEX, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
json.dump(vals, open(OUT_JSON, 'w'), indent=1)
print('\n'.join(lines[-3:]))
