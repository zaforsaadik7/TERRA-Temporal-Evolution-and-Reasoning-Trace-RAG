"""Phase 3 Batch 01: compute every value the batch binds, from primary artefacts. Read-only.
Usage: python -X utf8 p3b1_values.py <repo_root> <out_tex> <out_json>
Writes the proposed override file (phase3_corrections.tex) and a JSON of the recomputed values with sources.
Rounding: Python '{:.4f}' (the convention of the existing frozen macros, e.g. 0.03125 -> 0.0312) for p >= 1e-3; mantissa 2 dp (x 10^k) below 1e-3."""
import json, os, sys
from decimal import Decimal, ROUND_HALF_UP
from scipy.stats import binom

ROOT, OUT_TEX, OUT_JSON = sys.argv[1:4]
rs = json.load(open(os.path.join(ROOT, 'scratch', 'category_d_rubric_summary_v2.json'), encoding='utf-8'))
cv = json.load(open(os.path.join(ROOT, 'data', 'terra_canonical_v2_eval.json'), encoding='utf-8'))


def exact(b, c):
    n, k = b + c, min(b, c)
    return 1.0 if n == 0 else min(1.0, 2 * binom.cdf(k, n, 0.5))


def fmt(p):
    if p < 1e-3:
        m, e = f'{p:.2e}'.split('e')
        return f'\\ensuremath{{{m} \\times 10^{{{int(e)}}}}}'
    return f'{float(p):.4f}'  # same convention as the frozen generator macros (e.g. 0.03125 -> 0.0312)


BASE = [('1_Direct_LLM', 'DirectLLM'), ('2_Flat_Vector_RAG', 'FlatRAG'), ('3_GraphRAG_Adapted', 'GraphRAG'), ('4_HippoRAG_Adapted', 'HippoRAG')]
tests = []
for fam, key, tag in (('safe', 'mcnemar_safe_handling_paired', 'Safe'), ('refusal', 'mcnemar_explicit_refusal_paired', 'Refusal')):
    for p, s in BASE:
        c = rs[key][p]
        pv = float(exact(c['terra_win_b'], c['baseline_win_c']))
        assert abs(pv - c['exact_two_tailed_p']) <= 1e-12 * max(1.0, pv) or abs(pv - c['exact_two_tailed_p']) < 1e-15
        tests.append(dict(family=fam, baseline=p, macro=f'TerraVs{s}CatD{tag}McNemarP', holm_macro=f'TerraVs{s}CatD{tag}McNemarHolmP',
                          b=c['terra_win_b'], c=c['baseline_win_c'], p=pv))
# Holm over the declared 8-test secondary family
order = sorted(range(len(tests)), key=lambda i: tests[i]['p'])
m, run = len(tests), 0.0
for rank, i in enumerate(order):
    run = max(run, (m - rank) * tests[i]['p'])
    tests[i]['holm'] = min(1.0, run)
T = [r for r in cv if r['pipeline'] == '5_Full_TERRA' and r['category'].startswith('D')]
flag = sum(bool(r['safety_rejected']) for r in T)
flag_rate = 100 * flag / len(T)
lines = ['% ==========================================================================',
         '% PHASE 3 BATCH 01 CORRECTION OVERRIDES (generated by p3b1_values.py; do not hand-edit)',
         '% Loaded after generated_stats.tex. generated_stats.tex itself is untouched.',
         '% R35: stale pre-Issue-6 refusal McNemar literals replaced by exact two-tailed McNemar p from the',
         '%      v2 paired tables in scratch/category_d_rubric_summary_v2.json (mcnemar_explicit_refusal_paired).',
         '% User decision 2026-09-29: the 8 Category D McNemar tests (4 safe-handling, 4 explicit-refusal) form one',
         '%      declared SECONDARY family; Holm-adjusted p reported alongside exact p.',
         '% ==========================================================================']
for t in tests:
    if t['family'] == 'refusal':
        lines.append(f"\\renewcommand{{\\{t['macro']}}}{{{fmt(t['p'])}}} % R35: b={t['b']}, c={t['c']}")
for t in tests:
    lines.append(f"\\newcommand{{\\{t['holm_macro']}}}{{{fmt(t['holm'])}}} % Holm (8-test family): {t['family']} vs {t['baseline']}, b={t['b']}, c={t['c']}, exact p={t['p']:.6g}")
lines.append(f"\\newcommand{{\\TerraCatDFlaggedRefusals}}{{{flag}/{len(T)}}} % canonical v2 safety_rejected, Category D (system-flagged)")
lines.append(f"\\newcommand{{\\TerraCatDFlaggedRefusalRate}}{{{flag_rate:.1f}\\%}} % canonical v2 safety_rejected, Category D")
open(OUT_TEX, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
json.dump(dict(tests=tests, terra_catd_flagged=f'{flag}/{len(T)}', terra_catd_flagged_rate=round(flag_rate, 1),
               sources=dict(rubric='scratch/category_d_rubric_summary_v2.json', canonical='data/terra_canonical_v2_eval.json (95e775e2)')),
          open(OUT_JSON, 'w'), indent=1)
for t in tests:
    print(t['family'], t['baseline'], t['b'], t['c'], fmt(t['p']), fmt(t['holm']))
print('flagged D', flag, len(T), f'{flag_rate:.1f}')
