"""Phase 3 Batch 06: derive the override macros from the raw CaseFacts/CLERC files (read-only).
Usage: python -X utf8 p3b6_values.py <repo_root> <src_dir> <out_tex>"""
import json, os, re, sys
ROOT, SRC, OUT = sys.argv[1:4]
S = os.path.join(ROOT, 'scratch')
b = lambda x: x is True or str(x).lower() == 'true'
P = {'Direct': '1_Direct_LLM', 'Flat': '2_Flat_Vector_RAG', 'Terra': '5_Full_TERRA'}
L = ['Supported', 'Refuted', 'Overruled']
cf = json.load(open(os.path.join(S, 'casefacts_120_eval_raw.json'), encoding='utf-8'))
res = {}
for k, p in P.items():
    rs = [r for r in cf if r['pipeline'] == p]
    tp = {l: sum(r['ground_truth'] == l and r['parsed_label'] == l for r in rs) for l in L}
    pred = {l: sum(r['parsed_label'] == l for r in rs) for l in L}; sup = {l: sum(r['ground_truth'] == l for r in rs) for l in L}
    f1 = {}
    for l in L:
        pr = tp[l] / pred[l] if pred[l] else 0; rc = tp[l] / sup[l]; f1[l] = 2 * pr * rc / (pr + rc) * 100 if pr + rc else 0
    res[k] = dict(sr=(f1['Supported'] + f1['Refuted']) / 2, tp=sum(tp.values()), n=len(rs))
cl = json.load(open(os.path.join(S, 'clerc_120_eval_raw.json'), encoding='utf-8'))
t = [r for r in cl if r['pipeline'] == P['Terra']]
q = lambda r: b(r.get('eval_qwen', {}).get('hallucination_detected')); g = lambda r: b(r.get('eval_gpt_oss', {}).get('hallucination_detected'))
gen = [r for r in t if not b(r['generation'].get('refusal_short_circuit'))]
orr, andd = sum(q(r) or g(r) for r in gen), sum(q(r) and g(r) for r in gen)
ev = [r['retrieval_evaluation'] for r in t]
hf, ht = sum(b(e['flat_hit_top10']) for e in ev), sum(b(e['terra_hit_top10']) for e in ev)
gs = open(os.path.join(SRC, 'generated_stats.tex'), encoding='utf-8').read()
m = lambda k: re.search(r'\{\\' + k + r'\}\{([^}]*)\}', gs).group(1)
pp = lambda v: v.replace('\\%', '').replace('+', '+') + '\\,pp'
lines = [
 '% Phase 3 Batch 06 overrides (R09: CaseFacts and CLERC). Generated by p3b6_values.py from the raw scratch files; the frozen generated_stats.tex is not edited.',
 '\\renewcommand{\\CaseFactsTerraLiftFlat}{%s}' % pp(m('CaseFactsTerraLiftFlat')),
 '\\renewcommand{\\CaseFactsTerraLiftDirect}{%s}' % pp(m('CaseFactsTerraLiftDirect')),
 '\\newcommand{\\CaseFactsTerraMacroSR}{%.2f\\%%}' % res['Terra']['sr'],
 '\\newcommand{\\CaseFactsFlatMacroSR}{%.2f\\%%}' % res['Flat']['sr'],
 '\\newcommand{\\CaseFactsDirectMacroSR}{%.2f\\%%}' % res['Direct']['sr'],
 '\\newcommand{\\CaseFactsTerraAccCount}{%d/%d}' % (res['Terra']['tp'], res['Terra']['n']),
 '\\newcommand{\\CaseFactsBaselineAccCount}{%d/%d}' % (res['Flat']['tp'], res['Flat']['n']),
 '\\newcommand{\\ClercTerraMisappGenOr}{%.1f\\%% (%d/%d)}' % (100 * orr / len(gen), orr, len(gen)),
 '\\newcommand{\\ClercTerraMisappGenAnd}{%.1f\\%% (%d/%d)}' % (100 * andd / len(gen), andd, len(gen)),
 '\\newcommand{\\ClercTerraHitsTen}{%d/%d}' % (ht, len(t)),
 '\\newcommand{\\ClercFlatHitsTen}{%d/%d}' % (hf, len(t)),
]
assert res['Flat']['tp'] == res['Direct']['tp'], 'baseline accuracy counts differ'
open(OUT, 'w', encoding='utf-8', newline='').write('\r\n'.join(lines) + '\r\n')
print('\n'.join(lines))
